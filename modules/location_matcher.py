def _match_location_alias(location: str):
    """解析景點別名，並容許使用者加上正確的縣市前綴。"""
    direct_match = LOCATION_ALIASES.get(location)
    if direct_match:
        return direct_match

    for landmark, district in LOCATION_ALIASES.items():
        county = district[:3]
        county_short = county[:-1]
        if location in (f"{county}{landmark}", f"{county_short}{landmark}"):
            return district

    return None

